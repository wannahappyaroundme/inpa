export function getSearchHub(
  kind: SearchHubKind,
  slug: string,
): SearchHubContent | undefined {
  return SEARCH_HUBS.find((hub) => hub.kind === kind && hub.slug === slug);
}

export function getSearchHubPaths(): string[] {
  return SEARCH_HUBS.map((hub) => `/${hub.kind === "solution" ? "solutions" : "guides"}/${hub.slug}`);
}
